#!/usr/bin/env python3
"""Build device/colorui_demo.h from the simulator trace: a small set of REAL
Reticulum packets, the demo area boundaries and a host interfaces frame, so the
firmware's DEMO mode can show every page with no Reticulum setup at all."""
import sys
trace = sys.argv[1] if len(sys.argv) > 1 else "sim/trace.txt"
places = sys.argv[2] if len(sys.argv) > 2 else "sim/demo-places.bin"
out = sys.argv[3] if len(sys.argv) > 3 else "device/colorui_demo.h"
pk, host = [], None
for line in open(trace):
    if line.startswith("#"): continue
    t, kind, rest = line.split(" ", 2)
    if kind == "P":
        tx, rssi, snr, hexs = rest.split()
        if len(pk) < 48 and len(hexs) // 2 <= 400: pk.append((int(tx), int(rssi), float(snr), bytes.fromhex(hexs)))
    elif kind == "H" and rest.startswith("0101"):
        host = bytes.fromhex(rest.strip())
c = lambda b: ",".join(str(x) for x in b)
L = ["// Generated by tools/gen_demo.py -- real Reticulum packets for DEMO mode.", "#pragma once", "#include <stdint.h>",
     "struct DemoPkt { uint8_t tx; int16_t rssi; int8_t snr4; uint16_t len; const uint8_t* data; };"]
for i, (tx, r, s, d) in enumerate(pk):
    L.append(f"static const uint8_t kDemoP{i}[{len(d)}] = {{{c(d)}}};")
L.append("static const DemoPkt kDemoPkts[] = {")
for i, (tx, r, s, d) in enumerate(pk):
    L.append(f"  {{{tx}, {r}, {int(s*4)}, {len(d)}, kDemoP{i}}},")
L.append("};")
L.append(f"static const int kDemoPktCount = {len(pk)};")
pb = open(places, "rb").read()
L.append(f"static const uint8_t kDemoPlaces[{len(pb)}] = {{{c(pb)}}};")
L.append(f"static const uint8_t kDemoHost[{len(host)}] = {{{c(host)}}};")
# GPS drive: Fair Oaks -> Orangevale -> Folsom, then back, one point every 4 s
L.append("static const int32_t kDemoRoute[][2] = {")
pts = [(38.6450 + 0.020 * f / 40, -121.2700 + 0.110 * f / 40) for f in range(41)]
pts += pts[::-1][1:]
for la, lo in pts: L.append(f"  {{{int(la*1e6)}, {int(lo*1e6)}}},")
L.append("};")
L.append(f"static const int kDemoRouteLen = {len(pts)};")
open(out, "w").write("\n".join(L) + "\n")
print(len(pk), "packets,", len(pb), "byte places ->", out)
