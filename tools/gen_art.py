import math, json, sys, os
W,H=80,60
def scene(theme):
    g=[[None]*W for _ in range(H)]
    T={
     'day':dict(sky=['#3B7BD9','#4A8BE6','#5C9CF0','#73AEF5','#8EC2F8','#A8D4FA'],hill2='#5A8F6A',hill1='#3F7A4E',grass='#4CAF50',grass2='#3D9142',dirt='#8B5A2B',wall='#E8D3A8',wall2='#C9AF82',roof='#B23A3A',roof2='#8A2A2A',win='#7FD3FF',door='#6B3E1F',mast='#C8CED6',wave='#FFFFFF',pk=['#FF9F43','#3DD6F5','#B48CFF'],sun='#FFE066',cloud='#FFFFFF'),
     'sunset':dict(sky=['#2B1B4F','#4B2463','#7A2E6B','#B8445E','#E86A4A','#F7A440'],hill2='#5B2E4E',hill1='#3E2140',grass='#4E6B3A',grass2='#3B5230',dirt='#5E3A26',wall='#E3B98C',wall2='#B88A62',roof='#7A2E3A',roof2='#561F2A',win='#FFD36E',door='#4A2A18',mast='#D9C2B0',wave='#FFE7A8',pk=['#FF9F43','#3DD6F5','#B48CFF'],sun='#FFD36E',cloud='#F59A7A'),
     'night':dict(sky=['#05070F','#070B18','#0A1022','#0D162E','#111D3A','#16264A'],hill2='#18263A',hill1='#101B2A',grass='#1D3B2A',grass2='#152C1F',dirt='#2A1E16',wall='#5A5E78',wall2='#43465C',roof='#3A2A40',roof2='#2A1E30',win='#FFD36E',door='#2A1E16',mast='#8A94A6',wave='#3DD6F5',pk=['#FF9F43','#3DD6F5','#B48CFF'],sun='#F2F0DC',cloud='#2A3550'),
    }[theme]
    def px(x,y,c):
        if 0<=x<W and 0<=y<H: g[y][x]=c
    def rect(x,y,w,h,c):
        for j in range(y,y+h):
            for i in range(x,x+w): px(i,j,c)
    # sky bands with dithering
    bands=T['sky']; hz=38
    for y in range(hz):
        f=y/hz*(len(bands)-1); b=int(f); fr=f-b
        for x in range(W):
            c=bands[b]
            if b+1<len(bands) and fr>0.5 and (x+y)%2==0: c=bands[b+1]
            px(x,y,c)
    # sun / moon / stars
    if theme=='day':
        cx,cy,r=66,9,4
        for y in range(cy-r,cy+r+1):
            for x in range(cx-r,cx+r+1):
                if (x-cx)**2+(y-cy)**2<=r*r+1: px(x,y,T['sun'])
        for (x,y,w) in [(8,6,9),(30,10,7),(46,4,6)]:
            rect(x,y,w,2,T['cloud']); rect(x+2,y-1,w-4,1,T['cloud'])
    elif theme=='sunset':
        cx,cy,r=62,31,6
        for y in range(cy-r,hz):
            for x in range(cx-r,cx+r+1):
                if (x-cx)**2+(y-cy)**2<=r*r+1 and not (y%3==0 and y>cy): px(x,y,T['sun'])
        for (x,y,w) in [(6,12,10),(24,8,8),(40,15,9)]:
            rect(x,y,w,1,T['cloud']); rect(x+2,y+1,w-3,1,T['cloud'])
    else:
        import random; random.seed(7)
        for _ in range(45):
            x=random.randrange(W); y=random.randrange(30)
            px(x,y,'#FFFFFF' if random.random()<0.5 else '#9FB0C0')
        cx,cy,r=68,8,4
        for y in range(cy-r,cy+r+1):
            for x in range(cx-r,cx+r+1):
                if (x-cx)**2+(y-cy)**2<=r*r+1 and not ((x-cx-2)**2+(y-cy+1)**2<=r*r-2): px(x,y,T['sun'])
    # hills
    for x in range(W):
        h2=int(33+3*math.sin(x/7.0)+2*math.sin(x/3.1+1))
        for y in range(h2,hz+2): px(x,y,T['hill2'])
        h1=int(37+2*math.sin(x/5.0+2))
        for y in range(h1,hz+3): px(x,y,T['hill1'])
    # field
    for y in range(hz+2,H):
        for x in range(W):
            c=T['grass']
            if (x*3+y*7)%11==0 or ((y-hz)%4==0 and x%3==0): c=T['grass2']
            px(x,y,c)
    # dirt path from door toward bottom
    for y in range(50,H):
        off=(y-50)//2
        rect(17-off//2,y,4+off,1,T['dirt'])
    # grass tufts
    for (x,y) in [(40,52),(55,47),(70,55),(5,56),(48,58),(62,51),(30,57)]:
        px(x,y,T['grass2']); px(x-1,y-1,T['grass2']); px(x+1,y-1,T['grass2'])
    # fence
    for x in range(34,78):
        px(x,45,T['wall2'])
        if x%4==2: rect(x,43,1,4,T['wall2'])
    # house
    hx,hy,hw,hh=10,38,16,12
    rect(hx,hy,hw,hh,T['wall'])
    for j in range(hy,hy+hh): px(hx+hw-1,j,T['wall2'])
    rect(hx,hy+hh-1,hw,1,T['wall2'])
    # roof stepped
    for k in range(7):
        rect(hx-2+k,hy-1-k,hw+4-2*k,1,T['roof'] if k%2==0 else T['roof2'])
    # chimney
    rect(hx+3,hy-7,2,4,T['wall2'])
    if theme!='night': 
        for (x,y) in [(hx+4,hy-9),(hx+3,hy-11),(hx+5,hy-12)]: px(x,y,'#D0D6DE')
    # door & windows
    rect(hx+7,hy+5,3,7,T['door']); px(hx+9,hy+8,T['win'] if theme!='day' else '#E0C060')
    rect(hx+2,hy+3,3,3,T['win']); rect(hx+11,hy+3,3,3,T['win'])
    px(hx+3,hy+3,T['wall2']); px(hx+3,hy+4,T['wall2']); px(hx+3,hy+5,T['wall2'])
    px(hx+12,hy+3,T['wall2']); px(hx+12,hy+4,T['wall2']); px(hx+12,hy+5,T['wall2'])
    # antenna mast on roof
    mx=hx+12; top=hy-22
    rect(mx,top,1,hy-6-top+1,T['mast'])
    for k,(y,w) in enumerate([(top+3,5),(top+7,7),(top+11,5)]):
        rect(mx-w//2,y,w,1,T['mast'])
    px(mx,top-1,'#FF5050')  # tip light
    # guy wires
    for i in range(1,6):
        px(mx-i,top+10+i*2 if top+10+i*2<hy-6 else hy-7,T['mast'])
    return g, (mx, top)

def main(out):
    lines=["// Generated by tools/gen_art.py -- 8-bit background art (80x60, drawn at 4x).","#pragma once","#include <stdint.h>","namespace cui {"]
    ant=None
    for t in ["day","sunset","night"]:
        g,ant=scene(t)
        pal=[]
        idx=bytearray()
        for row in g:
            for c in row:
                c=c or "#000000"
                if c not in pal: pal.append(c)
                idx.append(pal.index(c))
        def rgb565(h):
            v=int(h[1:],16); r,gg,b=v>>16,(v>>8)&255,v&255
            return ((r&0xF8)<<8)|((gg&0xFC)<<3)|(b>>3)
        lines.append(f"static const uint16_t kArtPal_{t}[{len(pal)}] = {{"+", ".join(f"0x{rgb565(c):04x}" for c in pal)+"};")
        lines.append(f"static const uint8_t kArt_{t}[80*60] = {{")
        for i in range(0,len(idx),40): lines.append("  "+",".join(str(b) for b in idx[i:i+40])+",")
        lines.append("};")
    lines.append(f"static const int kArtAntX = {ant[0]}, kArtAntY = {ant[1]};  // antenna tip, art pixels")
    lines.append("}  // namespace cui")
    open(out,"w").write("\n".join(lines)+"\n")
if __name__=="__main__":
    main(sys.argv[1] if len(sys.argv)>1 else "core/cui_art.h")
