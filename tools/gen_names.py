#!/usr/bin/env python3
"""Generate core/cui_names.h: Reticulum name hashes for well-known app aspects.

A Reticulum announce carries the 10-byte name hash = SHA-256("app.aspect")[:10]
in plaintext, so the display can tell what kind of service announced
(an LXMF user, a NomadNet page server, a propagation node...) without
decrypting anything. Plain destinations (like path requests) have a fixed
address = SHA-256(name_hash)[:16].
"""
import hashlib, sys
SERVICES = [  # (aspect, short label, icon id)
    ("lxmf.delivery",                  "LXMF",  0),
    ("lxmf.propagation",               "PROP",  1),
    ("nomadnetwork.node",              "NOMAD", 2),
    ("lxst.telephony",                 "CALL",  3),
    ("rnstransport.discovery.interface","IFACE", 4),
    ("rnstransport.remote.management", "MGMT",  5),
]
PLAIN = [("rnstransport.path.request", "PATHREQ"), ("rnstransport.tunnel.synthesize", "TUNNEL")]
nh = lambda s: hashlib.sha256(s.encode()).digest()[:10]
c = lambda b: ", ".join(f"0x{x:02x}" for x in b)
out = ["// Generated by tools/gen_names.py -- do not edit.", "#pragma once", "#include <stdint.h>",
       "namespace cui {", "struct ServiceName { uint8_t hash[10]; const char* label; const char* aspect; uint8_t icon; };",
       "static const ServiceName kServices[] = {"]
for a, l, i in SERVICES: out.append(f'  {{{{{c(nh(a))}}}, "{l}", "{a}", {i}}},')
out.append("};")
out.append(f"static const int kServiceCount = {len(SERVICES)};")
for a, l in PLAIN:
    d = hashlib.sha256(nh(a)).digest()[:16]
    out.append(f"// plain destination {a}")
    out.append(f"static const uint8_t kDest_{l}[16] = {{{c(d)}}};")
out.append("}  // namespace cui")
open(sys.argv[1] if len(sys.argv) > 1 else "core/cui_names.h", "w").write("\n".join(out) + "\n")
