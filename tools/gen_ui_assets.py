#!/usr/bin/env python3
"""Generate the modern UI's anti-aliased fonts and icons as C++ data.

    python3 tools/gen_ui_assets.py <tabler icons outline dir>  -> core/cui_ui_assets.h

Fonts: Inter (SIL Open Font License), rendered with FreeType at fixed pixel
sizes into 4-bit alpha glyphs. Icons: Tabler Icons (MIT), outline set,
rasterized from SVG into 4-bit alpha masks.
Get the icons with:  npm pack @tabler/icons && tar xzf tabler-icons-*.tgz
"""
import io, os, sys
from PIL import Image, ImageDraw, ImageFont
import cairosvg

INTER = "/usr/share/fonts/opentype/inter/"
FONTS = [  # name, file, px, charset
    ("F_SM",    "Inter-Medium.otf",   10, None),
    ("F_BODY",  "Inter-Regular.otf",  12, None),
    ("F_BOLD",  "Inter-SemiBold.otf", 12, None),
    ("F_TITLE", "Inter-SemiBold.otf", 15, None),
    ("F_BIG",   "Inter-SemiBold.otf", 21, None),
    ("F_HUGE",  "InterDisplay-SemiBold.otf", 40, "0123456789:.-% APM"),
]
ASCII = "".join(chr(c) for c in range(32, 127))

ICONS = [  # enum name, tabler file, px
    ("I_HOME", "home"), ("I_LIST", "list-details"), ("I_CHART", "chart-line"),
    ("I_WAVE", "activity"), ("I_MAP", "map-pin"), ("I_NET", "network"),
    ("I_INFO", "info-circle"), ("I_ANT", "antenna-bars-5"), ("I_BCAST", "broadcast"),
    ("I_USERS", "users"), ("I_MSG", "message"), ("I_GPS", "current-location"),
    ("I_WIFI", "wifi"), ("I_USB", "usb"), ("I_BT", "bluetooth"), ("I_CLOCK", "clock"),
    ("I_WARN", "alert-triangle"), ("I_ROUTER", "router"), ("I_RADAR", "radar"),
    ("I_SAT", "satellite"), ("I_PLUG", "plug-connected"), ("I_SD", "device-sd-card"),
    ("I_MAIL", "mail"), ("I_ROUTE", "route"), ("I_CPU", "cpu"),
]
ICON_SIZES = [18, 13]


def nib(a):  # 0..255 -> 0..15
    return min(15, (a * 15 + 127) // 255)


def pack(img):
    w, h = img.size
    px = img.load()
    out = []
    for y in range(h):
        row = [nib(px[x, y]) for x in range(w)]
        if w % 2: row.append(0)
        for i in range(0, len(row), 2): out.append(row[i] << 4 | row[i + 1])
    return out


def gen_font(name, fname, px, charset):
    f = ImageFont.truetype(INTER + fname, px)
    asc, desc = f.getmetrics()
    chars = charset or ASCII
    glyphs, data = [], []
    for c in ASCII:
        if c not in chars:
            glyphs.append((0, 0, 0, 0, 0, 0)); continue
        adv = int(round(f.getlength(c)))
        x0, y0, x1, y1 = f.getbbox(c, anchor="ls")
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        if w == 0 or h == 0:
            glyphs.append((len(data), 0, 0, 0, 0, adv)); continue
        im = Image.new("L", (w, h), 0)
        ImageDraw.Draw(im).text((-x0, -y0), c, font=f, fill=255, anchor="ls")
        off = len(data); data += pack(im)
        glyphs.append((off, w, h, x0, y0, adv))   # y0 is relative to the baseline (negative = above)
    s = [f"// {fname} {px}px" + (f" (only \"{charset}\")" if charset else "")]
    s.append(f"static const uint8_t {name}_data[] = {{" + ",".join(map(str, data)) + "};")
    s.append(f"static const AAGlyph {name}_g[95] = {{" +
             ",".join("{%d,%d,%d,%d,%d,%d}" % g for g in glyphs) + "};")
    s.append(f"static const AAFont {name}_font = {{{name}_g, {name}_data, {asc}, {asc + desc}}};")
    return "\n".join(s), len(data)


def gen_icon(name, path, px):
    svg = open(path).read().replace('stroke-width="2"', 'stroke-width="%s"' % ("2" if px >= 16 else "2.25"))
    png = cairosvg.svg2png(bytestring=svg.encode(), output_width=px, output_height=px)
    a = Image.open(io.BytesIO(png)).convert("RGBA").split()[3]
    return pack(a)


def main():
    idir = sys.argv[1]
    out = ["// Generated by tools/gen_ui_assets.py -- do not edit.",
           "// Fonts: Inter (SIL OFL 1.1). Icons: Tabler Icons (MIT).",
           "#pragma once", "#include <stdint.h>", "namespace cui {",
           "struct AAGlyph { uint32_t off; uint8_t w, h; int8_t xo, yo; uint8_t adv; };",
           "struct AAFont { const AAGlyph* g; const uint8_t* data; uint8_t ascent, line; };"]
    total = 0
    for f in FONTS:
        s, n = gen_font(*f); out.append(s); total += n
    out.append("enum Icon : uint8_t { " + ", ".join(n for n, _ in ICONS) + ", I_COUNT };")
    for px in ICON_SIZES:
        blobs = [gen_icon(n, os.path.join(idir, f + ".svg"), px) for n, f in ICONS]
        out.append(f"static const uint8_t kIcon{px}[{len(ICONS)}][{len(blobs[0])}] = {{" +
                   ",".join("{" + ",".join(map(str, b)) + "}" for b in blobs) + "};")
        total += sum(len(b) for b in blobs)
    out.append("}  // namespace cui")
    open("core/cui_ui_assets.h", "w").write("\n".join(out) + "\n")
    print("core/cui_ui_assets.h:", total, "bytes of glyph/icon data")


main()
